# CRIE UMA VARIÁVEL INTEIRA E ATRIBUA UM VALOR ARBITRÁRIO A ELA, DE SUA PREFERÊNCIA. IMPRIMA SEU CONTEÚDO. EM SEGUIDA, UTILIZE OS OPERADORES DE ATRIBUIÇÃO ARITMÉTICA PARA:
# INCREMENTAR O CONTEÚDO DA VARIÁVEL EM 1 UNIDADE E IMPRIMIR NA TELA;
# DECREMENTAR O CONTEÚDO DA VARIÁVEL EM 1 UNIDADE E IMPRIMIR NA TELA;

dado = 10
print(f"Conteúdo da variável dado: {dado}")

dado += 1 # dado = dado + 1 
print(f"Conteúdo da variável dado, depois do incremento: {dado}")

dado -= 1 # dado = dado - 1
print(f"Conteúdo da variável dado, depois do decremento: {dado}")

# (CONTINUAÇÃO)
# DUPLICAR O CONTEÚDO DA VARIÁVEL EM MEMÓRIA, ATUALIZAR O CONTEÚDO DA VARIÁVEL, E IMPRIMIR O RESULTADO;
# CALCULAR A METADE DA VARIÁVEL EM MEMÓRIA, ATUALIZAR O CONTEÚDO DA VARIÁVEL, E IMPRIMIR O RESULTADO.

dado *= 2 # dado = dado * 2
print(f"Conteúdo da variável dado, depois da duplicação: {dado}")

dado /= 2 # dado = dado / 2
print(f"Conteúdo da variável dado, depois da divisão: {dado}")